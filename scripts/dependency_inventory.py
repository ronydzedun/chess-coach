"""Regenerate the license metadata inventory from the complete locked graph."""
import argparse
import json
from pathlib import Path
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
metadata = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=root
))
packages = sorted((p for p in metadata["packages"] if p["source"] is not None),
                  key=lambda p: (p["name"], p["version"]))
lines = ["# Locked dependency inventory", "",
         "Generated by `python3 scripts/dependency_inventory.py` from `cargo metadata --locked`.",
         "Includes registry packages for all resolved targets, not only the host build.",
         "Expressions are publisher declarations; see [licensing review](LICENSING.md) and `deny.toml`.", "",
         "| Package | Version | Declared license |",
         "| --- | --- | --- |"]
for package in packages:
    name, version = package["name"], package["version"]
    license_expression = package["license"]
    if not license_expression:
        raise SystemExit(f"Missing license metadata: {name} {version}")
    lines.append(f"| [{name}](https://docs.rs/crate/{name}/{version}/source/) | {version} | {license_expression} |")
content = "\n".join(lines) + "\n"
path = root / "docs" / "DEPENDENCIES.md"
if args.check:
    if not path.exists() or path.read_text() != content:
        raise SystemExit("Dependency inventory is stale; regenerate it")
    print(f"Inventory current: {len(packages)} registry packages")
else:
    path.write_text(content)
    print(f"Wrote {len(packages)} registry packages")
